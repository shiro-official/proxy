import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { test } from 'node:test';
import { createTelemetry } from '../server/telemetry.js';

test('telemetry preserves real zeros, gaps, and counter resets', (t) => {
  const db = new DatabaseSync(':memory:');
  t.after(() => db.close());
  const key = 'e'.repeat(64);
  const telemetry = createTelemetry(db, key);
  const start = Date.UTC(2026, 10, 21);
  const record = (minutes, values) => telemetry.record(values, start + minutes * 60_000);
  const sample = { telemt: true, connections: 0, bytes: 100, uptime: 100, wireguard: true, latency: 48.5 };
  assert.equal(telemetry.accepts({ headers: {} }), false);
  assert.equal(telemetry.accepts({ headers: { authorization: 'Bearer incorrect' } }), false);
  assert.equal(telemetry.accepts({ headers: { authorization: `Bearer ${key}` } }), true);
  assert.equal(telemetry.report('24h', start).connections, null);
  assert.throws(() => record(0, { telemt: false, connections: 0 }));
  assert.throws(() => record(0, { telemt: true, ingressIp: 'not an IP' }));
  record(0, sample);
  const first = telemetry.report('24h', start);
  assert.equal(first.connections, 0);
  assert.equal(first.latency, 48.5);
  assert.equal(first.traffic, null);
  record(1, { ...sample, connections: 15, bytes: 300, uptime: 160 });
  record(1, { ...sample, connections: 17, bytes: 400, uptime: 160 });
  record(2, { ...sample, connections: 9, bytes: 900, uptime: 10 });
  record(3, { ...sample, connections: 7, bytes: 900, uptime: 70 });
  record(20, { ...sample, connections: 4, bytes: 1400, uptime: 1090 });
  const report = telemetry.report('24h', start + 20 * 60_000);
  assert.equal(report.connections, 4);
  assert.deepEqual(report.traffic, { bytes: 300, coverageSeconds: 120 });
  assert.deepEqual(report.chart.points.map(({ value }) => value), [17, 4]);
  const stale = telemetry.report('7d', start + 25 * 60_000);
  assert.equal(stale.fresh, false);
  assert.equal(stale.connections, null);
  assert.equal(stale.latency, null);
  assert(Number.isFinite(stale.observedAt));
});
